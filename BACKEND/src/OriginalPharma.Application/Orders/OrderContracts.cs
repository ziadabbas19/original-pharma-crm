/// <param name="DiscountPercent">0 to 100, at most 2 decimals.</param>
public sealed record OrderLineInput(Guid ProductId, int Quantity, decimal DiscountPercent = 0);

/// <summary>
/// The editable part of an order. Exactly one of <paramref name="CollectionMethodId"/> and
/// <paramref name="CollectionMethodOther"/> must be set ("Other" means typing it).
/// </summary>
public interface IOrderInput
{
    DateOnly OrderDate { get; }
    PlaceType PlaceType { get; }
    string PlaceName { get; }
    Guid? CustomerId { get; }
    Guid? CollectionMethodId { get; }
    string? CollectionMethodOther { get; }
    string? Notes { get; }
    IReadOnlyList<OrderLineInput> Lines { get; }
}

