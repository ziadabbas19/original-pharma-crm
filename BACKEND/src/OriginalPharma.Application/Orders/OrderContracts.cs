internal static class OrderInputRules
{
    public static void Apply<T>(AbstractValidator<T> validator)
        where T : IOrderInput
    {
        validator.RuleFor(x => x.PlaceType).IsInEnum();
        validator.RuleFor(x => x.PlaceName).Must(n => !string.IsNullOrWhiteSpace(n)).WithMessage("Place name is required.")
            .MaximumLength(Order.PlaceNameMaxLength);
        validator.RuleFor(x => x.OrderDate).NotEmpty();
        validator.RuleFor(x => x.Notes).MaximumLength(Order.NotesMaxLength);
        validator.RuleFor(x => x.CustomerId).NotEqual(Guid.Empty);
        validator.RuleFor(x => x.CollectionMethodOther).MaximumLength(Order.OtherTextMaxLength);
        validator.RuleFor(x => x)
            .Must(input => HasExactlyOneCollectionMethod(input))
            .OverridePropertyName("CollectionMethodId")
            .WithMessage("Choose a collection method, or choose Other and type it (not both).");
        validator.RuleFor(x => x.Lines).NotEmpty().WithMessage("Add at least one product.")
            .Must(lines => lines is null || lines.Count <= 200).WithMessage("At most 200 lines per order.")
            .Must(lines => lines is null || lines.Select(l => l.ProductId).Distinct().Count() == lines.Count)
            .WithMessage("Each product can appear only once; change the quantity instead.");
        validator.RuleForEach(x => x.Lines).ChildRules(line =>
        {
            line.RuleFor(l => l.ProductId).NotEmpty();
            line.RuleFor(l => l.Quantity).InclusiveBetween(1, 1_000_000);
            line.RuleFor(l => l.DiscountPercent).InclusiveBetween(0, 100)
                .Must(d => decimal.Round(d, 2) == d).WithMessage("Discount can have at most 2 decimals.");
        });
    }

    /// <summary>The collection method rule on its own, so it can be checked (and tested) without a validator.</summary>
    public static bool HasExactlyOneCollectionMethod(IOrderInput input) =>
        input.CollectionMethodId is { } id && id != Guid.Empty
            ? string.IsNullOrWhiteSpace(input.CollectionMethodOther)
            : !string.IsNullOrWhiteSpace(input.CollectionMethodOther);
}

public sealed class CreateOrderRequestValidator : AbstractValidator<CreateOrderRequest>
{
    public CreateOrderRequestValidator()
    {
        RuleFor(x => x.ClientRequestId).NotEmpty();
        OrderInputRules.Apply(this);
    }
}

public sealed class UpdateOrderRequestValidator : AbstractValidator<UpdateOrderRequest>
{
    public UpdateOrderRequestValidator() => OrderInputRules.Apply(this);
}

public sealed class OrderStatusRequestValidator : AbstractValidator<OrderStatusRequest>
{
    public OrderStatusRequestValidator()
    {
        RuleFor(x => x.Reason).MaximumLength(500);
    }
}

